		add_filter( 'ep_weighted_query_for_post_type', array( $this, 'adjust_fuzzy_fields' ), 10, 3 );
		add_filter( 'ep_saved_weighting_configuration', array( $this, 'epio_send_autosuggest_public_request' ) );
		add_filter( 'wp', array( $this, 'epio_send_autosuggest_allowed' ) );
		add_filter( 'ep_pre_sync_index', array( $this, 'epio_send_autosuggest_public_request' ) );

		add_filter( 'ep_after_update_feature', [ $this, 'after_update_feature' ], 10, 3 );
		add_filter( 'ep_after_sync_index', [ $this, 'epio_save_search_template' ] );
		add_filter( 'ep_saved_weighting_configuration', [ $this, 'epio_save_search_template' ] );
		add_action( 'pre_get_posts', [ $this, 'maybe_apply_product_visibility' ] );
	}

